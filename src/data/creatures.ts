export interface CreatureTemplate {
  /** английское имя строчными, без пробелов и знаков: «Sun's Aegis» → sunsaegis */
  id: string
  name: { ru: string; en: string }
  faction: FactionId
  /** ранг существа: I–VII у фракций, до VIII у нейтралов */
  tier: number
  /**
   * Базовый прирост — сколько существ прибавляется за неделю. Одинаков у всех
   * существ одного ранга во фракции. Нет у нейтралов и у Огненной личинки:
   * их не нанимают в городе.
   */
  growth?: number
  /**
   * Улучшенное существо. В каждом ранге фракции — базовое существо и два
   * улучшения на выбор; у базового флага нет. Нет его и у нейтралов
   * с Огненной личинкой: в городе их не нанимают и не улучшают.
   */
  upgraded?: boolean
  hp: number
  attack: number
  defense: number
  damageMin: number
  damageMax: number
  /**
   * Бьёт, не вызывая ответного удара: стрелки, снайперы и «атака на расстоянии»
   * через гекс. У атакующего включает «Дистанционную атаку».
   */
  ranged?: boolean
  /**
   * −50% в ближнем бою: стрелки и снайперы. У защищающегося включает
   * «Контратаку 50%». У «атаки на расстоянии» такого штрафа нет.
   */
  counterHalved?: boolean
}

