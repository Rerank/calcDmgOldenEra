/**
 * Узкий экран: армии идут лентой, а в армии нет дыр — см. armyTransitions.ts.
 * Граница совпадает с медиазапросами (max-width: 900px) в CSS экрана армий:
 * меняешь здесь — меняй и там.
 */
const NARROW = '(max-width: 900px)'

/**
 * Проверяется в момент клика, а не подпиской на изменения: раскладка важна
 * только в момент правки, а перерисовывать экран при каждом повороте
 * планшета незачем.
 */
export const isNarrow = () => matchMedia(NARROW).matches
