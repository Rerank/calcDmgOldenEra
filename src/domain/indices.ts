import { RULES } from './rules'
import type { ArmyHero, ArmyStack, Indices } from './types'

/**
 * Индексы урона, живучести и мощности — общая математика сравнения армий
 * и рейтинга существ. Чистые функции, как и расчёт урона: на вход числа,
 * на выход числа.
 *
 * Армия сводится к двум индексам. Индекс урона — сколько она наносит за один
 * залп по цели с нулевой защитой, индекс живучести — сколько урона от удара
 * с нулевой атакой она выдержит. Настоящие защита цели и атака врага одинаковы
 * для всех сравниваемых и при сравнении сокращаются — знать их не нужно.
 *
 * Рейтинг существ — то же сравнение в другом представлении: существо — это
 * армия из одного отряда. Поштучно — из одного существа, с приростом —
 * из недельного прироста.
 */

const NO_HERO: ArmyHero = { attack: 0, defense: 0 }

/**
 * Допуск при сравнении. Суммы по разным отрядам складываются в разном
 * порядке и расходятся в последних знаках double: 0.1 + 0.2 — это
 * 0.30000000000000004, а 1 − 0.97 — 0.030000000000000027. Без допуска
 * равные значения не поделили бы лидерство и место, а отставание ровно
 * в 3% не считалось бы ничьей.
 */
export const EPSILON = 1e-9

/** Индексы набора отрядов — армии или одного отряда. */
export function indicesOf(stacks: ArmyStack[], hero: ArmyHero = NO_HERO): Indices {
  let damage = 0
  let hardiness = 0

  for (const { unit, count } of stacks) {
    const avgDamage = (unit.damageMin + unit.damageMax) / 2
    // бонус героя прибавляется к атаке и защите каждого существа армии
    damage += (count * avgDamage * (RULES.base + unit.attack + hero.attack)) / RULES.base
    hardiness += (count * unit.hp * (RULES.base + unit.defense + hero.defense)) / RULES.base
  }

  // Произведение, а не сумма: армия А уничтожит армию Б за H(Б) / D(А) ходов,
  // Б уничтожит А за H(А) / D(Б) — побеждает та, у кого D × H больше. Армия
  // с огромной живучестью, но без урона, никого не победит, а сумма оценила бы
  // её высоко. Корень возвращает масштаб: вдвое больше тех же существ — вдвое
  // больше мощности, поэтому проценты разницы читаются естественно.
  return { damage, hardiness, power: Math.sqrt(damage * hardiness) }
}

/** Доля от лучшего значения: 1 — лучшее, 0.5 — вдвое меньше. Лучшего нет (все нули) — 0. */
export const shareOf = (value: number, best: number) => (best > 0 ? value / best : 0)

/** Значения равны с точностью до погрешности дробных чисел. */
export const nearlyEqual = (a: number, b: number) =>
  Math.abs(a - b) <= EPSILON * Math.max(Math.abs(a), Math.abs(b))

/**
 * Место значения среди соперников, по убыванию: 1 плюс сколько из них
 * больше. Равные делят место, а следующее пропускается: 1, 2, 2, 4.
 * Само значение может быть в списке соперников — себя оно не обгоняет.
 */
export const placeAmong = (value: number, rivals: number[]) =>
  1 + rivals.filter((other) => other > value && !nearlyEqual(other, value)).length
